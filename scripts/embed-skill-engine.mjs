#!/usr/bin/env node
// Builds src/skill-exec/engine/embedded.ts: the hidden runner page (with its worker) as one string the app loads
// into a WebView. Run after editing engine.js, worker.js or page.js:  node scripts/embed-skill-engine.mjs
// Pass --check to fail when embedded.ts is out of date (used by CI).

import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/skill-exec/engine/', import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), 'utf8');

const worker = read('engine.js') + '\n' + read('worker.js');
const page = read('page.js').replace("'__WORKER_SRC__'", () => JSON.stringify(worker));
// No network: scripts and the worker come only from inline code and blobs; connect-src allows nothing but data.
const csp = "default-src 'none'; script-src 'unsafe-inline' 'unsafe-eval' 'wasm-unsafe-eval' blob:; worker-src blob:; connect-src data:; img-src data: blob:; style-src 'unsafe-inline'";
const html = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}"><title>runner</title></head><body><script>${page.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;

const out = `// Generated by scripts/embed-skill-engine.mjs from engine.js, worker.js and page.js. Don't edit by hand.\nexport const RUNNER_HTML = ${JSON.stringify(html)};\n`;
const target = new URL('embedded.ts', dir);
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(target, 'utf8');
  } catch {}
  if (cur !== out) {
    console.error('src/skill-exec/engine/embedded.ts is out of date: run node scripts/embed-skill-engine.mjs');
    process.exit(1);
  }
  console.log('embedded.ts is up to date');
} else {
  writeFileSync(target, out);
  console.log(`embedded.ts: ${(out.length / 1024).toFixed(0)} KB`);
}
